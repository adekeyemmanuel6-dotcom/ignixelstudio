// Generates src/lib/icons.generated.ts from Google Material Symbols (Rounded, weight 400).
// Run: node scripts/gen-icons.mjs   (needs devDependency @material-symbols/svg-400)
import fs from "node:fs";
const NAMES = ["arrow_forward","arrow_outward","arrow_back","arrow_upward","keyboard_arrow_down","menu","close","search","mail","call","location_on","check","check_circle","format_quote","download","star","add","language","palette","code","shopping_bag","explore","ads_click","layers","memory","forum","handshake","lightbulb","workspace_premium","verified_user","rocket_launch","groups","trending_up","north_east","bolt","north"];
const dir = "node_modules/@material-symbols/svg-400/rounded";
const out = {};
for (const n of NAMES) {
  const f = `${dir}/${n}.svg`;
  if (!fs.existsSync(f)) { console.error("missing", n); process.exit(1); }
  out[n] = [...fs.readFileSync(f, "utf8").matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(" ");
}
fs.writeFileSync("src/lib/icons.generated.ts", `// AUTO-GENERATED by scripts/gen-icons.mjs. Source: Google Material Symbols (Rounded, 400). Apache-2.0.\nexport const ICON_PATHS: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log("icons:", Object.keys(out).length);
